export const dictionaries: Record<Locale, Record<TranslationKey, string>> = { id, en };

export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>
) {
  const template = dictionaries[locale][key] ?? dictionaries.id[key] ?? key;
  if (!vars) return template;
  return Object.keys(vars).reduce((text, name) => {
    return text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(vars[name]));
  }, template);
}

